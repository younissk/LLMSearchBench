"""Attribution is generated, so the committed copies must not drift from the registry.

This is the same guard as `test_site_contract.py`, pointed at credit rather than
at schema: if someone edits SOURCES.md by hand, or adds a dataset without
regenerating, CI says so instead of the site quietly under-crediting a source.
"""

from __future__ import annotations

from pathlib import Path

from llmsearchbench.datasets import DATASETS
from llmsearchbench.datasets.attribution import (
    GENERATED_BANNER,
    render_bibtex,
    render_site_page,
    render_sources_markdown,
    write_all,
)
from llmsearchbench.paths import ATTRIBUTION, SITE_DOCS

SOURCES_MD = ATTRIBUTION / "SOURCES.md"
CITATIONS_BIB = ATTRIBUTION / "citations.bib"
SITE_PAGE = SITE_DOCS / "data-sources.md"


class TestCommittedFilesAreCurrent:
    def test_sources_markdown(self) -> None:
        assert SOURCES_MD.read_text(encoding="utf-8") == render_sources_markdown(), (
            "attribution/SOURCES.md is stale - run `make attribution`"
        )

    def test_citations_bib(self) -> None:
        assert CITATIONS_BIB.read_text(encoding="utf-8") == render_bibtex(), (
            "attribution/citations.bib is stale - run `make attribution`"
        )

    def test_site_page(self) -> None:
        assert SITE_PAGE.read_text(encoding="utf-8") == render_site_page(), (
            "docs/content/data-sources.md is stale - run `make attribution`"
        )


class TestContent:
    def test_every_dataset_appears_in_every_artefact(self) -> None:
        sources = render_sources_markdown()
        bibtex = render_bibtex()
        page = render_site_page()
        for spec in DATASETS.values():
            assert spec.title in sources
            assert spec.citation in sources
            assert spec.citation in bibtex
            assert spec.title in page

    def test_generated_files_say_they_are_generated(self) -> None:
        """Otherwise someone edits one by hand and loses the change."""
        assert GENERATED_BANNER in render_sources_markdown()
        assert GENERATED_BANNER in render_site_page()
        assert render_bibtex().startswith("% Generated by")

    def test_the_site_page_carries_frontmatter(self) -> None:
        page = render_site_page()
        assert page.startswith("---\n")
        assert "id: data-sources" in page

    def test_licence_and_checksum_are_shown_not_just_the_name(self) -> None:
        sources = render_sources_markdown()
        for spec in DATASETS.values():
            assert spec.license in sources
            for file in spec.files:
                assert file.sha256[:16] in sources


class TestWriteAll:
    def test_writes_into_the_given_directories(self, tmp_path: Path) -> None:
        written = write_all(
            attribution_dir=tmp_path / "attribution",
            site_docs=tmp_path / "content",
            lockfile=tmp_path / "datasets.lock.json",
        )
        assert [path.name for path in written] == [
            "SOURCES.md",
            "citations.bib",
            "data-sources.md",
            "datasets.lock.json",
        ]
        assert all(path.exists() for path in written)

    def test_rewriting_is_idempotent(self, tmp_path: Path) -> None:
        kwargs = {
            "attribution_dir": tmp_path / "attribution",
            "site_docs": tmp_path / "content",
            "lockfile": tmp_path / "datasets.lock.json",
        }
        write_all(**kwargs)  # type: ignore[arg-type]
        first = [path.read_text(encoding="utf-8") for path in write_all(**kwargs)]  # type: ignore[arg-type]
        second = [path.read_text(encoding="utf-8") for path in write_all(**kwargs)]  # type: ignore[arg-type]
        assert first == second
