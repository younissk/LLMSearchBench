"""Generated credit: licences, citations, and the site's data-sources page.

All of it is rendered from the dataset registry, so a dataset cannot be added
without its licence and citation appearing everywhere they should. Regenerate
with `make attribution`; the test suite fails if the committed files drift.
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from pathlib import Path

from llmsearchbench.datasets.registry import DATASETS, lockfile_contents
from llmsearchbench.datasets.spec import DatasetSpec
from llmsearchbench.paths import ATTRIBUTION, DATASETS_LOCK, LICENSES, SITE_DOCS
from llmsearchbench.ui.format import human_size

GENERATED_BANNER = (
    "<!-- Generated by `make attribution` from src/llmsearchbench/datasets/registry.py. "
    "Do not edit by hand. -->"
)


def render_sources_markdown(specs: Iterable[DatasetSpec] | None = None) -> str:
    """`attribution/SOURCES.md` — what we use, from whom, under which licence."""
    datasets = list(specs if specs is not None else DATASETS.values())

    lines = [
        GENERATED_BANNER,
        "",
        "# Data sources",
        "",
        "Every dataset this benchmark builds on, who produced it, and the terms it",
        "comes under. Licence texts as received are in [`licenses/`](licenses/);",
        "citations in machine-readable form are in [`citations.bib`](citations.bib).",
        "",
        "| Dataset | Licence | Files | Size | Pinned at |",
        "| --- | --- | --- | --- | --- |",
    ]

    for spec in datasets:
        pin = f"`{spec.pinned_commit[:10]}`" if spec.pinned_commit else "—"
        lines.append(
            f"| [{spec.title}]({spec.homepage}) | {spec.license} | "
            f"{len(spec.files)} | {human_size(spec.total_bytes)} | {pin} |"
        )

    for spec in datasets:
        lines += ["", f"## {spec.title}", ""]
        lines.append(spec.description)
        lines += ["", f"- **Homepage:** <{spec.homepage}>"]
        if spec.paper_url:
            lines.append(f"- **Paper:** <{spec.paper_url}>")
        lines.append(f"- **Licence:** {spec.license} — [text](licenses/{spec.license_file})")
        if spec.pinned_commit:
            lines.append(f"- **Pinned commit:** `{spec.pinned_commit}`")
        if spec.tags:
            lines.append(f"- **Tags:** {', '.join(spec.tags)}")

        lines += ["", "| File | Size | SHA-256 | What it is |", "| --- | --- | --- | --- |"]
        for file in spec.files:
            lines.append(
                f"| `{file.name}` | {human_size(file.size_bytes)} | "
                f"`{file.sha256[:16]}…` | {file.description} |"
            )

        if spec.notes:
            lines += ["", f"**Why this one.** {spec.notes}"]

        lines += ["", "```bibtex", spec.citation, "```"]

    return "\n".join(lines) + "\n"


def render_bibtex(specs: Iterable[DatasetSpec] | None = None) -> str:
    """`attribution/citations.bib` — every citation, verbatim as the authors publish it."""
    datasets = list(specs if specs is not None else DATASETS.values())
    header = [
        "% Generated by `make attribution` from src/llmsearchbench/datasets/registry.py.",
        "% Do not edit by hand.",
        "",
    ]
    entries = [f"% {spec.title} — {spec.homepage}\n{spec.citation}\n" for spec in datasets]
    return "\n".join(header) + "\n".join(entries)


def render_site_page(specs: Iterable[DatasetSpec] | None = None) -> str:
    """`docs/content/data-sources.md` — the same credit, on the published site."""
    datasets = list(specs if specs is not None else DATASETS.values())

    lines = [
        "---",
        "id: data-sources",
        "title: Data sources",
        "sidebar_position: 7",
        "description: The datasets LLMSearchBench builds on, and the terms they come under.",
        "---",
        "",
        GENERATED_BANNER,
        "",
        "# Data sources",
        "",
        "This benchmark does not invent its questions from nothing. Everything below",
        "was produced by someone else, and is used under the licence shown. Each file",
        "is pinned to a SHA-256 so a run can be reproduced against the same bytes.",
        "",
        "| Dataset | Licence | Size | Pinned at |",
        "| --- | --- | --- | --- |",
    ]

    for spec in datasets:
        pin = f"`{spec.pinned_commit[:10]}`" if spec.pinned_commit else "—"
        lines.append(
            f"| [{spec.title}]({spec.homepage}) | {spec.license} | "
            f"{human_size(spec.total_bytes)} | {pin} |"
        )

    for spec in datasets:
        lines += ["", f"## {spec.title}", "", spec.description, ""]
        if spec.paper_url:
            lines.append(f"Paper: [{spec.paper_url}]({spec.paper_url})")
            lines.append("")
        if spec.notes:
            lines += [":::note Why this one", "", spec.notes, "", ":::", ""]
        lines += ["```bibtex", spec.citation, "```"]

    lines += [
        "",
        "## Fetching them",
        "",
        "```bash",
        "make data          # download everything, skipping what is already verified",
        "make data-verify   # check what is on disk against the pinned checksums",
        "```",
        "",
        "Raw data is never committed. `data/datasets.lock.json` is, so the pins",
        "travel with the repository.",
    ]

    return "\n".join(lines) + "\n"


def write_all(
    *,
    attribution_dir: Path | None = None,
    site_docs: Path | None = None,
    lockfile: Path | None = None,
) -> list[Path]:
    """Write every generated attribution artefact. Returns what was written."""
    attribution_root = attribution_dir or ATTRIBUTION
    docs_root = site_docs or SITE_DOCS
    lock_path = lockfile or DATASETS_LOCK

    sources = attribution_root / "SOURCES.md"
    bibtex = attribution_root / "citations.bib"
    page = docs_root / "data-sources.md"

    for path, text in (
        (sources, render_sources_markdown()),
        (bibtex, render_bibtex()),
        (page, render_site_page()),
    ):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    lock_path.parent.mkdir(parents=True, exist_ok=True)
    lock_path.write_text(
        json.dumps(lockfile_contents(), indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    return [sources, bibtex, page, lock_path]


def missing_license_files(attribution_dir: Path | None = None) -> list[str]:
    """Datasets whose licence text we have not actually saved."""
    root = (attribution_dir or ATTRIBUTION) / "licenses" if attribution_dir else LICENSES
    return [
        spec.license_file
        for spec in DATASETS.values()
        if not (root / spec.license_file).exists()
    ]
